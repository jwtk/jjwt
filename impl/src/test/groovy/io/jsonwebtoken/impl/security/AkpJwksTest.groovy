        try {
            Jwks.builder().key(priv).build()
            fail()
        } catch (InvalidKeyException expected) {
            assertTrue expected.getMessage().contains('publicKey')
        }
    }

    @Test
    void testMismatchedPublicKeyParameterSet() {
