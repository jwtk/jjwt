    @Test
    void testPublicBuilderPrivateKeyChaining() {
        if (!available()) return
        def pair = seedRetainingKeyPair(MlDsaAlgorithm.ML_DSA_65)
        def jwk = Jwks.builder().akpKey(pair.getPublic()).privateKey(pair.getPrivate()).build() as AkpPrivateJwk
        assertEquals 'AKP', jwk.getType()
        assertEquals pair.getPublic(), jwk.toPublicJwk().toKey()
    }

    @Test
    void testAkpKeyPair() {
        if (!available()) return
        def alg = MlDsaAlgorithm.ML_DSA_44
        def pair = seedRetainingKeyPair(alg)
        byte[] seed = alg.getSeed(pair.getPrivate())
        assertEquals MlDsaAlgorithm.SEED_LENGTH, seed.length
        def jwk = Jwks.builder().akpKeyPair(pair).build() as AkpPrivateJwk
        assertEquals alg.getId(), jwk.getAlgorithm()
        assertEquals pair.getPublic(), jwk.toPublicJwk().toKey()
    }

