    @Test
    void testIdFromThumbprint() {
        if (!available()) return
        def pair = seedRetainingKeyPair(MlDsaAlgorithm.ML_DSA_65)
        def jwk = Jwks.builder().akpKeyPair(pair).idFromThumbprint().build() as AkpPrivateJwk
        assertNotNull jwk.getId()
        // the private JWK id must equal the one computed for the public JWK per RFC 7638 Section 3.2.1:
        assertEquals jwk.toPublicJwk().getId(), jwk.getId()
    }

    @Test
    void testThumbprintUsesRfc9964Members() {
        if (!available()) return
        def alg = MlDsaAlgorithm.ML_DSA_44
        def pub = keyPair(alg).getPublic()
        def jwk = Jwks.builder().key(pub).build()
        // RFC 9964 requires the AKP thumbprint to be computed over alg, kty and pub, in that order:
        assertEquals(['alg', 'kty', 'pub'], DefaultAkpPublicJwk.THUMBPRINT_PARAMS.collect { it.getId() })
        assertNotNull jwk.thumbprint()
    }

    @Test
    void testEqualsAndHashCode() {
        if (!available()) return
        def pub44 = keyPair(MlDsaAlgorithm.ML_DSA_44).getPublic()
        def jwk44a = Jwks.builder().key(pub44).build()
        def jwk44b = Jwks.builder().key(pub44).build()
        assertEquals jwk44a, jwk44b
        assertEquals jwk44a.hashCode(), jwk44b.hashCode()

        def jwk65 = Jwks.builder().key(keyPair(MlDsaAlgorithm.ML_DSA_65).getPublic()).build()
        assertNotEquals jwk44a, jwk65

        def ecJwk = Jwks.builder().key(TestKeys.ES256.pair.public).build()
        assertNotEquals jwk44a, ecJwk

        byte[] seed = Bytes.random(MlDsaAlgorithm.SEED_LENGTH)
        def priv44 = MlDsaAlgorithm.ML_DSA_44.toPrivateKey(seed, null)
        def privJwk1 = Jwks.builder().akpKey(priv44).publicKey(pub44).build()
        def privJwk2 = Jwks.builder().akpKey(priv44).publicKey(pub44).build()
        assertEquals privJwk1, privJwk2
        assertEquals privJwk1.hashCode(), privJwk2.hashCode()
        assertNotEquals privJwk1, jwk44a // private vs public

        def rsaPrivJwk = Jwks.builder().key(TestKeys.RS256.pair.private).build()
        assertNotEquals privJwk1, rsaPrivJwk
    }
}
