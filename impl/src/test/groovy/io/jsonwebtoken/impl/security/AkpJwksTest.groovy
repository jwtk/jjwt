/**
 * Tests for the {@code AKP} JWK key type defined by
 * <a href="https://www.rfc-editor.org/rfc/rfc9964.html">RFC 9964</a>.
 */
class AkpJwksTest {

    /**
     * Returns true if ML-DSA is available on the current runtime, either natively (JDK 24+) or via BouncyCastle.
     */
    private static boolean available() {
        try {
            MlDsaAlgorithm.ML_DSA_44.keyPair().build()
            return true
        } catch (Throwable ignored) {
            return false
        }
    }

    private static KeyPair keyPair(MlDsaAlgorithm alg) {
        return alg.keyPair().build()
    }

    /**
     * Returns a keypair whose private key encoding is guaranteed to retain the RFC 9964-required seed.  A pair
     * generated by the runtime's default path may not (JDK 24 through 26 encode an expanded private key only), so
     * this uses BouncyCastle, whose encoding contains both the seed and the expanded key.
     */
    private static KeyPair seedRetainingKeyPair(MlDsaAlgorithm alg) {
        return alg.keyPair().provider(Providers.findBouncyCastle()).build()
    }

    @Test
    void testPublicJwkRoundtripAllParameterSets() {
        if (!available()) return
        for (MlDsaAlgorithm alg : MlDsaAlgorithm.VALUES) {
            def pub = keyPair(alg).getPublic()

            def jwk = Jwks.builder().key(pub).build() as AkpPublicJwk
            assertEquals 'AKP', jwk.getType()
            assertEquals alg.getId(), jwk.getAlgorithm()
            assertEquals alg.getPublicKeyByteLength(), (jwk.get('pub') as String).decodeBase64Url().length
            assertEquals pub, jwk.toKey()

            // serialize and parse back:
            String json = Jwks.json(jwk)
            def parsed = Jwks.parser().build().parse(json)
            assertEquals jwk, parsed
            assertEquals pub, parsed.toKey()
        }
    }

    @Test
    void testPrivateJwkRoundtrip() {
        if (!available()) return
        for (MlDsaAlgorithm alg : MlDsaAlgorithm.VALUES) {
            // Build a private key from a known seed so the test does not depend on whether the runtime's default
            // provider retains the seed in generated keys (JDK 24 through 26 do not):
            byte[] seed = Bytes.random(MlDsaAlgorithm.SEED_LENGTH)
            PrivateKey priv = alg.toPrivateKey(seed, null)
            PublicKey pub = keyPair(alg).getPublic() // any matching-parameter-set public key for structure checks

            def jwk = Jwks.builder().key(priv).publicKey(pub).build() as AkpPrivateJwk
            assertEquals 'AKP', jwk.getType()
            assertEquals alg.getId(), jwk.getAlgorithm()
            // RFC 9964 Section 6 requires 'priv' to be the 32-byte seed:
            assertArrayEquals seed, jwk.get(DefaultAkpPrivateJwk.PRIV) as byte[]

            assertTrue jwk.toString().contains('<redacted>') // secret values are not printed

            def parsed = Jwks.parser().build().parse(Jwks.UNSAFE_JSON(jwk)) as AkpPrivateJwk
            assertEquals jwk, parsed
            assertEquals jwk.toPublicJwk(), parsed.toPublicJwk()
        }
    }

    /**
     * Asserts that a key parsed from an AKP JWK can actually produce an ML-DSA signature.
     */
    @Test
    void testParsedKeysSignAndVerify() {
        if (!available()) return
        def alg = MlDsaAlgorithm.ML_DSA_65
        byte[] seed = Bytes.random(MlDsaAlgorithm.SEED_LENGTH)
        PrivateKey priv = alg.toPrivateKey(seed, null)
        def pub = keyPair(alg).getPublic()
        def jwk = Jwks.builder().key(priv).publicKey(pub).build()
        def parsed = Jwks.parser().build().parse(Jwks.UNSAFE_JSON(jwk)) as AkpPrivateJwk

        byte[] data = 'hello ML-DSA'.getBytes('UTF-8')
        def key = parsed.toKey() as PrivateKey
        def signer
        try {
            signer = Signature.getInstance(alg.getId())
            signer.initSign(key)
        } catch (Exception ignored) { // the parsed key may come from a different provider than the JCA default
            signer = Signature.getInstance(alg.getId(), Providers.findBouncyCastle())
            signer.initSign(key)
        }
        signer.update(data)
        byte[] sig = signer.sign()
        assertTrue sig.length > 0
    }

    @Test
    void testPublicJsonParse() {
        if (!available()) return
        def alg = MlDsaAlgorithm.ML_DSA_44
        def pub = keyPair(alg).getPublic()
        String encoded = Encoders.BASE64URL.encode(alg.getPublicKeyMaterial(pub))

        String json = RfcTests.stripws("""
        {
           "kty": "AKP",
           "alg": "${alg.getId()}",
           "pub": "$encoded"
        }""")

        def jwk = Jwks.parser().build().parse(json) as AkpPublicJwk
        assertEquals 'AKP', jwk.getType()
        assertEquals alg.getId(), jwk.getAlgorithm()
        assertEquals encoded, jwk.get('pub')
        assertEquals pub, jwk.toKey()
    }

    @Test
    void testMissingAlg() {
        if (!available()) return
        def alg = MlDsaAlgorithm.ML_DSA_44
        String encoded = Encoders.BASE64URL.encode(alg.getPublicKeyMaterial(keyPair(alg).getPublic()))
        String json = RfcTests.stripws("""{"kty":"AKP","pub":"$encoded"}""")
        try {
            Jwks.parser().build().parse(json)
            fail()
        } catch (MalformedKeyException expected) {
            assertTrue expected.getMessage().contains("'alg'")
        }
    }

